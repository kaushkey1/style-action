// ─── Helper Functions ────────────────────────────────────────────────

/** Look up a KPI by ID. Returns first match (some IDs have variants). */
export function getKpiById(id: string): KpiDefinition | undefined {
  return kpiRegistry.find((k) => k.id === id);
}

/** Get all KPIs for a given category. */
export function getKpisByCategory(category: KpiCategory): KpiDefinition[] {
  return kpiRegistry.filter((k) => k.category === category);
}

/** Get all KPIs monitored by a specific agent. */
export function getKpisByAgent(agentId: string): KpiDefinition[] {
  return kpiRegistry.filter((k) => k.monitoringAgent === agentId);
}

/** Get Primary KPIs for a role. */
export function getPrimaryKpisForRole(role: string): KpiDefinition[] {
  return kpiRegistry.filter((k) => k.primaryForRoles.includes(role));
}

/** Get all KPIs applicable to a role (Primary + Secondary). */
export function getAllKpisForRole(role: string): KpiDefinition[] {
  return kpiRegistry.filter((k) => k.applicableRoles.includes(role));
}

