// Retail Calendar Journey — N-Day backward calendar mock data

export type JourneyPhase = 'PLAN' | 'BUY' | 'MAKE' | 'MOVE' | 'SELL';
export type AutonomyTier = 'T1' | 'T2' | 'T3' | 'T4';
export type MilestoneStatus = 'completed' | 'on-track' | 'at-risk' | 'missed' | 'upcoming';

export interface JourneyMilestone {
  id: string;
  name: string;
  phase: JourneyPhase;
  nDayLabel: string;
  targetDate: string;
  status: MilestoneStatus;
  agentId: string;
  agentName: string;
  autonomy: AutonomyTier;
  humanGate?: string;
  hardGuardrail?: string;
  exceptionSeverity: 'S1' | 'S2' | 'S3' | 'S4';
  dependencies?: string[];
  description: string;
  platform?: string;
}

export interface DropJourney {
  id: string;
  name: string;
  categoryPod: string;
  season: string;
  sourcingEngine: 'fast_response' | 'scale_margin' | 'test_repeat';
  nDay: string;
  milestones: JourneyMilestone[];
  postLaunch?: JourneyMilestone[];
  healthScore: number;
  status: 'on-track' | 'at-risk' | 'delayed' | 'completed';
}

export interface CalendarAlert {
  id: string;
  type: 'milestone_miss' | 'approaching_deadline' | 'cascade_risk' | 'resource_conflict';
  severity: 'S1' | 'S2' | 'S3' | 'S4';
  dropId: string;
  milestoneId: string;
  title: string;
  description: string;
  impact?: string;
  agentId: string;
  agentName: string;
  time: string;
  cascadeChain?: string[];
}

