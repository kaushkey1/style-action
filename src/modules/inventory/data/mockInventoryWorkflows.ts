// ─── TYPES ──────────────────────────────────────────────────────────────────

/** Step in a workflow chain */
export interface WorkflowStep {
  step_number: number;
  name: string;
  description: string;
  agent_id: string;
  agent_name: string;
  status: 'completed' | 'active' | 'pending' | 'skipped' | 'failed' | 'blocked';
  started_at: string | null;
  completed_at: string | null;
  requires_approval: boolean;
  approval_tier: 'T1' | 'T2' | 'T4' | null;
  approver_role: string | null;
  auto_approve_hours: number | null;
  auto_approve_at: string | null;
  outcome: string | null;
}

/** Active workflow instance — a specific breach flowing through its resolution chain */
export interface ActiveWorkflow {
  id: string;
  workflow_type:
    | 'stockout_replen_cascade'
    | 'broken_set_mandate'
    | 'forced_exit_transfer'
    | 'markdown_waterfall'
    | 'vendor_switch_cascade'
    | 'noos_size_breach'
    | 'rotation_violation'
    | 'clearance_escalation';
  workflow_label: string;
  trigger_event: string;
  triggered_at: string;
  triggered_by_agent: string;
  triggered_by_agent_name: string;
  sku: string;
  style_name: string;
  category: string;
  store_name: string | null;
  steps: WorkflowStep[];
  current_step_index: number;
  status: 'active' | 'blocked' | 'completed' | 'escalated';
  priority: 'critical' | 'high' | 'medium' | 'low';
  sla_deadline: string | null;
  sla_remaining_hours: number | null;
  sla_breached: boolean;
  linked_modules: ('inventory' | 'ar' | 'approvals' | 'exceptions' | 'store-view')[];
  linked_ids: { module: string; id: string; label: string }[];
  value_at_risk_lakh: number;
}

/** Dual-clock entry — Store Age vs Network Age for rotation detection */
export interface DualClockEntry {
  id: string;
  sku: string;
  style_name: string;
  category: string;
  store_id: string;
  store_name: string;
  store_grade: 'A+' | 'A1' | 'A2' | 'A3';
  network_age_days: number;
  store_age_days: number;
  transfer_count: number;
  rotation_flagged: boolean;
  transfer_blocked: boolean;
  reversal_required: boolean;
  audit_required: boolean;
  current_phase: 'A0_A1' | 'A2_A3' | 'clearance';
  sell_through_pct: number;
  flagged_by_agent: string | null;
}

/** Hard block on re-cut PO */
export interface HardBlockEntry {
  id: string;
  block_type: 'SIZE_RATIO_DEVIATION' | 'COVER_BREACH' | 'LARGE_LOT_UNPROVEN';
  block_label: string;
  sku: string;
  style_name: string;
  category: string;
  po_id: string;
  po_quantity: number;
  block_reason: string;
  threshold: string;
  actual_value: string;
  triggered_at: string;
  triggered_by_agent: string;
  override_status: 'blocked' | 'override_requested' | 'override_approved' | 'override_rejected';
  override_approver: string | null;
  override_justification: string | null;
  override_at: string | null;
  value_lakh: number;
}

/** Agent-to-workflow mapping — which agent owns which inventory workflow */
export interface AgentWorkflowMapping {
  agent_id: string;
  agent_name: string;
  ha_level: 'HA1' | 'HA2' | 'HA3' | 'HA4';
  domain: string;
  workflows: {
    workflow_type: string;
    workflow_label: string;
    trigger: string;
    human_approval_required: boolean;
    approval_tier: 'T1' | 'T2' | 'T4' | null;
    approver_role: string | null;
    auto_approve_hours: number | null;
    sla_hours: number | null;
  }[];
}

/** Inventory-specific pending approval (bridges to HumanGate pattern) */
export interface InventoryApproval {
  id: string;
  workflow_id: string;
  gate_type:
    | 'sm-validation'
    | 'phase-transition'
    | 'liquidation-routing'
    | 'chase-order'
    | 'below-cost-markdown'
    | 'forced-exit'
    | 'vendor-switch'
    | 'hard-block-override';
  title: string;
  approval_tier: 'T1' | 'T2' | 'T4';
  approver_role: string;
  dual_sign_off: string | null;
  agent_id: string;
  agent_name: string;
  sku: string;
  style_name: string;
  category: string;
  value_impact_lakh: number;
  requested_at: string;
  sla_deadline: string;
  sla_hours: number;
  auto_approve_at: string | null;
  hours_remaining: number;
  status: 'pending' | 'approved' | 'rejected' | 'escalated' | 'auto_approved';
  recommendation: string;
  context_points: { label: string; value: string; status?: 'on-track' | 'warning' | 'critical' }[];
}

