export type ExceptionSeverity = 'S1' | 'S2' | 'S3' | 'S4';
export type ExceptionStatus = 'agent-reviewing' | 'awaiting-approval' | 'resolved' | 'investigating' | 'agent-analyzing'
  | 'agent-acted' | 'escalated' | 'human-overridden' | 'monitoring' | 'closed-with-learning';
export type ExceptionDetectionType =
  | 'Threshold Breach'
  | 'Trend Deviation'
  | 'Milestone Miss'
  | 'Correlation Break'
  | 'Cross-system Conflict'
  | 'Pattern Match'
  | 'Cascade Risk';
export type ExceptionDomain = 'PLAN' | 'BUY' | 'MAKE' | 'MOVE' | 'SELL' | 'MARKET' | 'PLATFORM' | 'LIQUIDATION';
export type LifecycleStage = 'PRE_SEASON' | 'IN_SEASON' | 'END_OF_SEASON';

export interface CascadeStep {
  system: string;
  description: string;
}

export interface AgentRecommendation {
  agent: string;
  action: string;
}

